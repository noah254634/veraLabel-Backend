import mongoose from "mongoose";
import UserVera from "../../users/user.model.js"
const LabellerSchema=new mongoose.Schema({
    userId:{
        type:mongoose.Schema.Types.ObjectId,
        required:true,
        ref:"UserVera"
    },
    languages:{
        type:[String],
        required:false,
    },
    isOnboarded:{
        type:Boolean,
        default:false
    },
    gender:{
        type:String,
        enum:['male','female','other'],
        default:'male'
    },
    age:{
        type:Number,
        required:true
    },
    expertise:{
        type:[String],
        required:true
    },
    assignedTasks:{
        type:[mongoose.Schema.Types.ObjectId],
        ref:"Task"
    },
    completedTasks:{
        type:[mongoose.Schema.Types.ObjectId],
        ref:"Task"
    },
    skillTags:{
        type:[String],
        required:true
    },
    tier:{
        type:String,
        enum:['Trainee','Bronze','Silver','Gold'],
        default:'Trainee'
    },
    reliabilityScore:{
        type:Number,
        default:0
    },
    userLevel:{
        type:String,
        enum:['beginner','advanced','pro'],
        default:'beginner'
    },
    createdAt:{
        type:Date,
        default:Date.now
    },
    labellerTotalEarnings:{
        type:Number,
        default:0
    },
    location:{
        country:{
            type:String,
            required:true
        },
        region:{
            type:String,
            required:true
        },
        city:{
            type:String,
            required:true
        }
    },
    annotationExperience:{
        hasExperience:{
            type:Boolean,
            default:false
        },
        experienceDuration:{
            type:String,
            default:0
        },
    }
    



})
export default mongoose.model("Labeller",LabellerSchema)